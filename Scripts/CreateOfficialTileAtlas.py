"""Lossless official pixels, native tile order and native statue palette mapping."""
from pathlib import Path
import json,re,math,hashlib
from PIL import Image
root=Path(__file__).resolve().parents[1];out=root/'Art/TileFallback';out.mkdir(parents=True,exist_ok=True)
images=[];records=[];monster_data=None
gray=[0,1,17,18,19,20,27,22,23,24,25,26,21,15,13,14,14,1,17,18,19,20,27,22,23,24,25,20]
def read(category,statue=False):
    text=(root/'upstream/NetHack/win/share'/(category+'.txt')).read_text(encoding='utf-8')
    colors=[(m[0],tuple(map(int,m[1:]))) for m in re.findall(r'^(\S)\s*=\s*\(\s*(\d+),\s*(\d+),\s*(\d+)\s*\)',text,re.M)]
    palette={c:(colors[gray[i]][1] if statue and i<len(gray) else rgb) for i,(c,rgb) in enumerate(colors)}
    entries=re.findall(r'^# tile (\d+) \(([^\n]+)\)\s*(?:#[^\n]*\n\s*)*\{([^}]+)\}',text,re.M)
    for index,label,pixels in entries:
        lines=[s.strip() for s in pixels.strip().splitlines()];assert len(lines)==16 and all(len(s)==16 for s in lines)
        im=Image.new('RGBA',(16,16));im.putdata([(*palette[c],0 if c=='.' else 255) for line in lines for c in line])
        assert int(index)==len([r for r in records if r['source']==category and r['statue']==statue])
        records.append(dict(tile_index=len(images),source=category,source_index=int(index),label=label,statue=statue));images.append(im)
for name in ['monsters','objects','other']:read(name)
read('monsters',True)
columns=math.ceil(math.sqrt(len(images)));rows=math.ceil(len(images)/columns);stride=20;padding=2
atlas=Image.new('RGBA',(columns*stride,rows*stride))
for i,im in enumerate(images):atlas.paste(im,((i%columns)*stride+padding,(i//columns)*stride+padding))
atlas.save(out/'OfficialTiles.png')
data=dict(tile_count=len(images),columns=columns,rows=rows,stride=stride,padding=padding,pixels=16,width=atlas.width,height=atlas.height,tiles=records)
(out/'atlas.json').write_text(json.dumps(data,indent=2),encoding='utf-8')
mapping=(root/'upstream/NetHack/src/tile.c').read_text(encoding='utf-8')
indices=[int(n) for n in re.findall(r'NO_CUSTOMCOLOR,\s+NO_CUSTOMCOLOR,\s+(\d+),\s+0\s*}',mapping)]
assert indices and max(indices)<len(images)
bottoms=[15-max((y for y in range(16) for x in range(16) if im.getpixel((x,y))[3]),default=15) for im in images]
demo_monster=next(r['tile_index'] for r in records if r['source']=='monsters' and r['label']=='minotaur,male' and not r['statue'])
demo_item=next(r['tile_index'] for r in records if r['source']=='objects' and r['label']=='purple-red / healing')
header='// Generated by CreateOfficialTileAtlas.py from official source pixels.\n#pragma once\n'+f'constexpr int32 OfficialTileCount={len(images)};\n'
header+=f'constexpr int32 OfficialTileDemoMonster={demo_monster},OfficialTileDemoItem={demo_item};\n'
header+='constexpr uint8 OfficialTileBottomPadding[]={'+','.join(str(b) for b in bottoms)+'};\n'
(root/'Source/NUthEck/OfficialTileAtlas.h').write_text(header,encoding='utf-8')
print('OFFICIAL_TILE_ATLAS_READY '+json.dumps({k:v for k,v in data.items() if k!='tiles'}))
